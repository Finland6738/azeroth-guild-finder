-- M2.4: the navigation of the main window as plain Lua (UI/Nav.lua): role -> tabs (SPEC-00 §5), the page stack, the
-- book of tabs and stacks, window scale and position. No frames are involved here.

local function nav() return AzerothGuildFinder.Nav end

describe("Nav.TabsFor: role -> tabs", function()
	it("puts Settings first for every role and state", function()
		for _, role in ipairs({ "none", "member", "officer", "gm" }) do
			for _, listing in ipairs({ false, true }) do
				eq(nav().TabsFor(role, listing)[1], "Settings", role .. " " .. tostring(listing))
			end
		end
	end)

	it("a player without a guild sees Find a Guild and My Application", function()
		deepEq(nav().TabsFor("none", false), { "Settings", "FindGuild", "MyApplication" })
		deepEq(nav().TabsFor("none", true), { "Settings", "FindGuild", "MyApplication" })
	end)

	it("a member sees only My Guild, listing or not", function()
		deepEq(nav().TabsFor("member", true), { "Settings", "MyGuild" })
		deepEq(nav().TabsFor("member", false), { "Settings", "MyGuild" })
	end)

	it("an officer sees My Guild, and Applications only when the guild has a listing", function()
		deepEq(nav().TabsFor("officer", false), { "Settings", "MyGuild" })
		deepEq(nav().TabsFor("officer", true), { "Settings", "MyGuild", "Applications" })
	end)

	it("a Guild Master sees Create Listing alone, then My Guild and Applications once listed", function()
		deepEq(nav().TabsFor("gm", false), { "Settings", "CreateListing" })
		deepEq(nav().TabsFor("gm", true), { "Settings", "MyGuild", "Applications" })
	end)

	it("a player in a guild never sees the search", function()
		for _, role in ipairs({ "member", "officer", "gm" }) do
			for _, listing in ipairs({ false, true }) do
				for _, tab in ipairs(nav().TabsFor(role, listing)) do ne(tab, "FindGuild") end
			end
		end
	end)

	it("follows the panels of Core/Role exactly, with Settings in front", function()
		for _, role in ipairs({ "none", "member", "officer", "gm" }) do
			for _, listing in ipairs({ false, true }) do
				local panels = AzerothGuildFinder.Role.PanelsFor(role, listing)
				local tabs = nav().TabsFor(role, listing)
				eq(#tabs, #panels + 1)
				for i, panel in ipairs(panels) do eq(tabs[i + 1], panel) end
			end
		end
	end)

	it("an unknown role is treated as a player without a guild", function()
		deepEq(nav().TabsFor("nonsense", false), { "Settings", "FindGuild", "MyApplication" })
	end)

	it("every tab has a label key that exists and a glyph", function()
		for id, tab in pairs(nav().TABS) do
			local label = AzerothGuildFinder.Widgets and tab.labelKey
			truthy(label, id)
			truthy(tab.glyph, id)
			ne(LibStub("AceLocale-3.0"):GetLocale("AzerothGuildFinder")[tab.labelKey], tab.labelKey, "translated " .. id)
		end
	end)

	it("the default tab is the first one of the role, or Settings when there is none", function()
		eq(nav().DefaultTab({ "Settings", "FindGuild", "MyApplication" }), "FindGuild")
		eq(nav().DefaultTab({ "Settings" }), "Settings")
		eq(nav().DefaultTab({}), "Settings")
	end)
end)

describe("Nav page stack", function()
	it("starts with its root and cannot go back", function()
		local s = nav().NewStack("FindGuild")
		eq(s:Depth(), 1)
		eq(s:Top().page, "FindGuild")
		falsy(s:CanGoBack())
		isNil(s:Back())
		eq(s:Depth(), 1)
	end)

	it("pushes pages and goes back through them in order", function()
		local s = nav().NewStack("FindGuild")
		s:Push("GuildPage", { k = "a" })
		s:Push("Editor")
		eq(s:Depth(), 3)
		deepEq(s:Pages(), { "FindGuild", "GuildPage", "Editor" })
		truthy(s:CanGoBack())
		local left, now = s:Back()
		eq(left.page, "Editor")
		eq(now.page, "GuildPage")
		eq(now.params.k, "a")
		s:Back()
		eq(s:Top().page, "FindGuild")
		isNil(s:Back())
	end)

	it("keeps the state a page saved when it is left", function()
		local s = nav().NewStack("FindGuild")
		s:SaveState({ search = "bro", scroll = 120 })
		s:Push("GuildPage", { k = "x" })
		s:SaveState({ scroll = 5 })
		s:Back()
		deepEq(s:GetState(), { search = "bro", scroll = 120 })
	end)

	it("a page pushed again starts with an empty state", function()
		local s = nav().NewStack("FindGuild")
		s:Push("GuildPage")
		s:SaveState({ scroll = 40 })
		s:Back()
		s:Push("GuildPage")
		deepEq(s:GetState(), {})
	end)

	it("Replace swaps the top page and Reset goes back to a single page", function()
		local s = nav().NewStack("A")
		s:Push("B")
		s:Replace("C", { n = 1 })
		deepEq(s:Pages(), { "A", "C" })
		eq(s:Top().params.n, 1)
		s:Push("D")
		s:Reset()
		deepEq(s:Pages(), { "A" })
		s:Reset("Z")
		deepEq(s:Pages(), { "Z" })
	end)

	it("never grows past MAX_DEPTH and keeps the root", function()
		local s = nav().NewStack("root")
		for i = 1, nav().MAX_DEPTH + 10 do s:Push("p" .. i) end
		eq(s:Depth(), nav().MAX_DEPTH)
		eq(s:Root().page, "root")
		eq(s:Top().page, "p" .. (nav().MAX_DEPTH + 10))
	end)
end)

describe("Nav book: tabs with one stack each", function()
	local kinds
	local function book()
		kinds = {}
		return nav().NewBook(function(kind) kinds[#kinds + 1] = kind end)
	end

	it("selects the first tab of the role when the tabs are set", function()
		local b = book()
		truthy(b:SetTabs({ "Settings", "FindGuild", "MyApplication" }))
		eq(b:Current(), "FindGuild")
		eq(b:Page().page, "FindGuild")
		deepEq(kinds, { "tabs" })
	end)

	it("a role with no tab besides Settings opens on Settings", function()
		local b = book()
		b:SetTabs({ "Settings" })
		eq(b:Current(), "Settings")
	end)

	it("drops tab ids it does not know and never ends up with no tab", function()
		local b = book()
		b:SetTabs({ "Settings", "Bogus", "FindGuild" })
		deepEq(b:Tabs(), { "Settings", "FindGuild" })
		b:SetTabs({ "Bogus" }, true)
		deepEq(b:Tabs(), { "Settings" })
	end)

	it("Select changes the tab and refuses one the role does not have", function()
		local b = book()
		b:SetTabs({ "Settings", "FindGuild", "MyApplication" })
		truthy(b:Select("MyApplication"))
		eq(b:Current(), "MyApplication")
		falsy(b:Select("MyGuild"))
		eq(b:Current(), "MyApplication")
		truthy(b:Select("MyApplication"), "selecting the current tab is fine")
	end)

	it("keeps one page stack per tab", function()
		local b = book()
		b:SetTabs({ "Settings", "FindGuild", "MyApplication" })
		b:Push("GuildPage", { k = "g1" })
		eq(b:Page().page, "GuildPage")
		truthy(b:CanGoBack())
		b:Select("MyApplication")
		eq(b:Page().page, "MyApplication")
		falsy(b:CanGoBack())
		b:Select("FindGuild")
		eq(b:Page().page, "GuildPage", "the page of the other tab is still there")
		truthy(b:Back())
		eq(b:Page().page, "FindGuild")
		falsy(b:Back())
	end)

	it("Home goes back to the root page of the tab", function()
		local b = book()
		b:SetTabs({ "Settings", "FindGuild" })
		b:Push("A"); b:Push("B")
		truthy(b:Home())
		eq(b:Page().page, "FindGuild")
		falsy(b:Home())
	end)

	it("tells the window what happened", function()
		local b = book()
		b:SetTabs({ "Settings", "FindGuild", "MyApplication" })
		b:Select("MyApplication")
		b:Push("X")
		b:Back()
		b:Select("FindGuild")
		b:Push("Y")
		b:Home()
		deepEq(kinds, { "tabs", "select", "push", "back", "select", "push", "home" })
	end)

	it("the same tabs again change nothing and keep the stacks", function()
		local b = book()
		b:SetTabs({ "Settings", "FindGuild" })
		b:Push("GuildPage")
		falsy(b:SetTabs({ "Settings", "FindGuild" }))
		eq(b:Page().page, "GuildPage")
		eq(#kinds, 2)
	end)

	it("a tab that stays keeps its stack and the selection when other tabs change", function()
		local b = book()
		b:SetTabs({ "Settings", "MyGuild" })
		b:Push("Page")
		truthy(b:SetTabs({ "Settings", "MyGuild", "Applications" }))
		eq(b:Current(), "MyGuild")
		eq(b:Page().page, "Page")
	end)

	it("a change of role (reset) starts again on the first tab of the new role", function()
		local b = book()
		b:SetTabs({ "Settings", "FindGuild", "MyApplication" })
		b:Select("MyApplication")
		b:Push("Something")
		truthy(b:SetTabs({ "Settings", "MyGuild" }, true))
		eq(b:Current(), "MyGuild")
		eq(b:Page().page, "MyGuild")
		falsy(b:Has("MyApplication"))
	end)

	it("reset also starts again when the tabs are the same", function()
		local b = book()
		b:SetTabs({ "Settings", "FindGuild" })
		b:Select("Settings")
		b:Push("X")
		truthy(b:SetTabs({ "Settings", "FindGuild" }, true))
		eq(b:Current(), "FindGuild")
		eq(b:Page().page, "FindGuild")
	end)

	it("the current tab is replaced when its tab disappears", function()
		local b = book()
		b:SetTabs({ "Settings", "CreateListing" })
		b:Select("CreateListing")
		b:SetTabs({ "Settings", "MyGuild", "Applications" })
		eq(b:Current(), "MyGuild")
	end)
end)

describe("Nav scale", function()
	it("clamps to 60 %..140 % in whole percent", function()
		eq(nav().ClampScale(1), 1)
		eq(nav().ClampScale(0.2), 0.6)
		eq(nav().ClampScale(0.6), 0.6)
		eq(nav().ClampScale(1.4), 1.4)
		eq(nav().ClampScale(3), 1.4)
		eq(nav().ClampScale(0.854), 0.85)
		eq(nav().ClampScale(-5), 0.6)
	end)

	it("a value that is not a number gives 100 %", function()
		eq(nav().ClampScale(nil), 1)
		eq(nav().ClampScale("big"), 1)
		eq(nav().ClampScale(0 / 0), 1)
		eq(nav().ClampScale(math.huge), 1)
	end)

	it("writes a scale as a percentage", function()
		eq(nav().ScaleLabel(1), "100%")
		eq(nav().ScaleLabel(0.6), "60%")
		eq(nav().ScaleLabel(1.4), "140%")
		eq(nav().ScaleLabel(9), "140%")
	end)

	it("reads what the player types", function()
		eq(nav().ParseScale("80"), 0.8)
		eq(nav().ParseScale(" 120 % "), 1.2)
		eq(nav().ParseScale("60"), 0.6)
		eq(nav().ParseScale("140"), 1.4)
		isNil(nav().ParseScale("59"))
		isNil(nav().ParseScale("141"))
		isNil(nav().ParseScale("big"))
		isNil(nav().ParseScale("80.5"))
		isNil(nav().ParseScale(""))
		isNil(nav().ParseScale(nil))
	end)

	it("does not change a scale that fits the screen", function()
		eq(nav().FitScale(1, 1920, 1080, 1116, 768, 92), 1)
		eq(nav().FitScale(1.4, 3840, 2160, 1116, 768, 92), 1.4)
	end)

	it("reduces a scale that would leave the screen", function()
		local fit = nav().FitScale(1.4, 1920, 1080, 1116, 768, 92)
		truthy(fit < 1.4 and fit > 0.6, fit)
		-- the whole book, the rail and the close button fit in the screen at that scale
		truthy((1116 + 92 + 12) * fit <= 1920 and (768 + 12) * fit <= 1080)
		local small = nav().FitScale(1, 1024, 600, 1116, 768, 92)
		truthy(small < 0.8, small)
	end)

	it("falls back to the clamped scale when the screen size is unknown", function()
		eq(nav().FitScale(1.2, nil, nil), 1.2)
		eq(nav().FitScale(1.2, 0, 0), 1.2)
	end)
end)

describe("Nav position", function()
	it("a saved position keeps its place on the screen when the scale changes", function()
		local saved = nav().PosToSaved("TOPLEFT", "TOPLEFT", 100, -50, 0.8)
		eq(saved.x, 80)
		eq(saved.y, -40)
		local point, relPoint, x, y = nav().SavedToPos(saved, 0.8)
		eq(point, "TOPLEFT"); eq(relPoint, "TOPLEFT"); eq(x, 100); eq(y, -50)
		local _, _, x2 = nav().SavedToPos(saved, 1)
		eq(x2, 80, "at 100 % the same screen place is 80 units from the anchor")
	end)

	it("a saved position is a valid Config position", function()
		local saved = nav().PosToSaved("CENTER", nil, 10, 20, 1.2)
		truthy(AzerothGuildFinder.Config.IsPos(saved))
		eq(saved.relPoint, "CENTER")
	end)

	it("the default position is valid and a little left of the centre", function()
		truthy(AzerothGuildFinder.Config.IsPos(nav().DEFAULT_POS))
		truthy(nav().DEFAULT_POS.x < 0)
	end)
end)
