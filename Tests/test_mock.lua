describe("C_EncodingUtil", function()
	-- the game's globals are rebuilt for every test: look C_EncodingUtil up when it is used, not when the file loads
	local enc = setmetatable({}, { __index = function(_, key) return C_EncodingUtil[key] end })

	it("Base64 round trips and matches the standard", function()
		eq(enc.EncodeBase64("Man"), "TWFu")
		eq(enc.EncodeBase64("Ma"), "TWE=")
		eq(enc.EncodeBase64("M"), "TQ==")
		eq(enc.DecodeBase64("TWE="), "Ma")
		local binary = ""
		for i = 0, 255 do binary = binary .. string.char(i) end
		eq(enc.DecodeBase64(enc.EncodeBase64(binary)), binary)
		local url = enc.EncodeBase64("\251\255\254", Enum.Base64Variant.StandardUrlSafe)
		eq(url, "-__-")
		eq(enc.DecodeBase64(url, Enum.Base64Variant.StandardUrlSafe), "\251\255\254")
		raises(function() enc.DecodeBase64("a") end, "invalid")
		raises(function() enc.DecodeBase64("@@@@") end, "invalid")
	end)

	it("hex round trips", function()
		eq(enc.EncodeHex("\0\255A"), "00ff41")
		eq(enc.DecodeHex("00ff41"), "\0\255A")
		raises(function() enc.DecodeHex("zz") end, "invalid")
	end)

	it("CBOR matches known encodings (RFC 8949 appendix A)", function()
		local function hex(v) return enc.EncodeHex(enc.SerializeCBOR(v)) end
		eq(hex(0), "00")
		eq(hex(23), "17")
		eq(hex(24), "1818")
		eq(hex(1000), "1903e8")
		eq(hex(1000000), "1a000f4240")
		eq(hex(-1), "20")
		eq(hex(-1000), "3903e7")
		eq(hex(1.1), "fb3ff199999999999a")
		eq(hex(-4.1), "fbc010666666666666")
		eq(hex(true), "f5")
		eq(hex("IETF"), "6449455446")
		eq(hex({ 1, 2, 3 }), "83010203")
		eq(hex({ a = 1, b = { 2, 3 } }), "a26161016162820203")
		eq(hex({}), "80")
	end)

	it("CBOR round trips every value kind", function()
		local value = {
			v = 1, t = "ANN", name = "H\195\169llo", ratio = 0.1, big = 2 ^ 40, neg = -123456, flags = { true, false },
			nested = { list = { 1, 2, { x = "y" } } }, huge = 1e300, tiny = 5e-324,
		}
		deepEq(enc.DeserializeCBOR(enc.SerializeCBOR(value)), value)
		eq(enc.DeserializeCBOR("\249\60\0"), 1.0)              -- half precision 1.0
		eq(enc.DeserializeCBOR("\250\71\195\80\0"), 100000.0)  -- single precision
	end)

	it("CBOR rejects malformed input with an error, never garbage", function()
		raises(function() enc.DeserializeCBOR("") end, "truncated")
		raises(function() enc.DeserializeCBOR("\131\1\2") end, "longer than the data")
		raises(function() enc.DeserializeCBOR("\1\2") end, "trailing")
		raises(function() enc.DeserializeCBOR("\31") end, "unsupported")
		raises(function() enc.SerializeCBOR({ f = print }) end, "cannot serialize")
		eq(enc.EncodeHex(enc.SerializeCBOR({ f = print }, { ignoreSerializationErrors = true })), "a16166f6")
	end)

	it("compression round trips with all three methods and shrinks repetitive data", function()
		local text = string.rep("guild finder ", 100)
		for _, method in pairs(Enum.CompressionMethod) do
			local packed = enc.CompressString(text, method, Enum.CompressionLevel.Default)
			truthy(#packed < #text / 4)
			eq(enc.DecompressString(packed, method), text)
		end
		eq(enc.CompressString(text, Enum.CompressionMethod.Gzip):sub(1, 2), "\31\139")
		raises(function() enc.DecompressString("not compressed", Enum.CompressionMethod.Zlib) end, "DecompressString")
		raises(function() enc.DecompressString(enc.CompressString(text, 1):sub(1, 10), 1) end, "DecompressString")
	end)
end)

describe("channels and chat windows (M1.8)", function()
	it("shows a new channel in the first window, lists channels in order and moves them", function()
		eq(Mock.chat.AddChannel("A"), 1)
		eq(Mock.chat.AddChannel("B"), 2)
		eq(Mock.chat.AddChannel("A"), 1, "joining twice is the same channel")
		truthy(Mock.chat.Showing("a", 1))
		falsy(Mock.chat.Showing("A", 2))
		deepEq({ GetChannelList() }, { 1, "A", false, 2, "B", false })
		C_ChatInfo.SwapChatChannelsByChannelIndex(1, 2)
		eq(GetChannelName("A"), 2)
		eq(GetChannelName("B"), 1)
		raises(function() C_ChatInfo.SwapChatChannelsByChannelIndex(9, 1) end, "bad index")
	end)

	it("ChatFrame_RemoveChannel and AddChannel change what a window shows", function()
		Mock.chat.AddChannel("A")
		ChatFrame_RemoveChannel(ChatFrame1, "A")
		falsy(Mock.chat.Showing("A"))
		ChatFrame_AddChannel(ChatFrame4, "A")
		truthy(Mock.chat.Showing("A", 4))
		eq(NUM_CHAT_WINDOWS, 10)
		truthy(ChatFrame10)
	end)

	it("runs the message filters per window and records what reaches a window", function()
		Mock.chat.AddChannel("A")
		Mock.chat.AddChannel("B")
		ChatFrame_AddMessageEventFilter("CHAT_MSG_CHANNEL", function(_, _, _, _, _, _, _, _, _, _, name) return name == "B" end)
		Mock.chat.DeliverChannelEvent("CHAT_MSG_CHANNEL", "x", "S", "", "1. A", "", 0, 0, 1, "A", 0, 0)
		Mock.chat.DeliverChannelEvent("CHAT_MSG_CHANNEL", "y", "S", "", "2. B", "", 0, 0, 2, "B", 0, 0)
		eq(#Mock.chat.displayed, 1)
		eq(Mock.chat.displayed[1].channel, "A")
		raises(function() ChatFrame_AddMessageEventFilter("CHAT_MSG_CHANNEL", "no") end, "bad arguments")
	end)

	it("joins refuse above maxChannels, with a notice code, or silently, as the controls say", function()
		Mock.chat.maxChannels = 2
		Mock.chat.AddChannel("A")
		Mock.chat.AddChannel("B")
		JoinChannelByName("C")
		Mock.Advance(0.2)
		eq(GetChannelName("C"), 0)
		Mock.chat.maxChannels = 10
		local notices = {}
		local f = CreateFrame("Frame")
		f:RegisterEvent("CHAT_MSG_CHANNEL_NOTICE")
		f:SetScript("OnEvent", function(_, _, kind) notices[#notices + 1] = kind end)
		Mock.chat.joinNotice = "THROTTLED"
		JoinChannelByName("C")
		Mock.Advance(0.2)
		eq(GetChannelName("C"), 0)
		deepEq(notices, { "THROTTLED" })
		Mock.chat.joinNotice = nil
		Mock.chat.joinIgnored = true
		JoinChannelByName("C")
		Mock.Advance(0.2)
		eq(#notices, 1)
		Mock.chat.joinIgnored = false
		JoinChannelByName("C")
		Mock.Advance(0.2)
		deepEq(notices, { "THROTTLED", "YOU_JOINED" })
		LeaveChannelByName("C")
		deepEq(notices, { "THROTTLED", "YOU_JOINED", "YOU_LEFT" })
		eq(GetChannelName("C"), 0)
	end)
end)
