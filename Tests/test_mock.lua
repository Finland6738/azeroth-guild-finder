-- Tests of the mock client itself: they pin the behaviour later tests rely on.

describe("clock and timers", function()
	it("time moves only through Mock.Advance", function()
		local t0, s0 = GetTime(), GetServerTime()
		eq(GetTime(), t0)
		Mock.Advance(2.5)
		near(GetTime() - t0, 2.5, 1e-6)
		eq(GetServerTime() - s0, 2)
	end)

	it("date and time are UTC and follow the fake epoch", function()
		eq(date("%Y-%m-%d %H:%M:%S", GetServerTime()), "2026-01-01 00:00:00")
		eq(time({ year = 2026, month = 1, day = 2, hour = 0 }), GetServerTime() + 86400)
		eq(time(), GetServerTime())
	end)

	it("C_Timer.After fires once, in order, after its delay", function()
		local log = {}
		C_Timer.After(2, function() log[#log + 1] = "b" end)
		C_Timer.After(1, function() log[#log + 1] = "a" end)
		Mock.Advance(0.5)
		deepEq(log, {})
		Mock.Advance(1)
		deepEq(log, { "a" })
		Mock.Advance(5)
		deepEq(log, { "a", "b" })
	end)

	it("a ticker repeats, stops after its iterations and can be cancelled", function()
		local n, m = 0, 0
		C_Timer.NewTicker(1, function() n = n + 1 end, 3)
		local ticker = C_Timer.NewTicker(1, function() m = m + 1 end)
		Mock.Advance(10)
		eq(n, 3)
		eq(m, 10)
		ticker:Cancel()
		Mock.Advance(5)
		eq(m, 10)
		truthy(ticker:IsCancelled())
		eq(Mock.PendingTimers(), 0)
	end)

	it("a timer created inside a callback waits for a later frame", function()
		local log = {}
		C_Timer.After(0, function()
			log[#log + 1] = "outer"
			C_Timer.After(0, function() log[#log + 1] = "inner" end)
		end)
		Mock.Advance(0.1)
		deepEq(log, { "outer" })
		Mock.Advance(0.1)
		deepEq(log, { "outer", "inner" })
	end)

	it("runs OnUpdate of visible frames with the elapsed time", function()
		local total, frames = 0, 0
		local f = CreateFrame("Frame")
		f:SetScript("OnUpdate", function(_, elapsed) total = total + elapsed; frames = frames + 1 end)
		Mock.Advance(1)
		near(total, 1, 1e-6)
		eq(frames, 10)
		f:Hide()
		Mock.Advance(1)
		eq(frames, 10)
	end)
end)

describe("frames and events", function()
	it("delivers events to registered frames only", function()
		local got = {}
		local a, b = CreateFrame("Frame"), CreateFrame("Frame")
		a:RegisterEvent("GUILD_ROSTER_UPDATE")
		a:SetScript("OnEvent", function(_, event, ...) got[#got + 1] = { event, ... } end)
		b:SetScript("OnEvent", function() got[#got + 1] = "b" end)
		Mock.Fire("GUILD_ROSTER_UPDATE", 1, 2)
		deepEq(got, { { "GUILD_ROSTER_UPDATE", 1, 2 } })
		a:UnregisterEvent("GUILD_ROSTER_UPDATE")
		Mock.Fire("GUILD_ROSTER_UPDATE")
		eq(#got, 1)
	end)

	it("rejects event names the Forever client does not have (when the API dump is present)", function()
		if not Mock.validEvents then return end
		raises(function() CreateFrame("Frame"):RegisterEvent("NOT_A_REAL_EVENT") end, "unknown event")
		raises(function() Mock.Fire("NOT_A_REAL_EVENT") end, "not an event")
	end)

	it("catches errors in handlers like the client does and reports them to the test", function()
		local f = CreateFrame("Frame")
		f:RegisterEvent("PLAYER_LOGIN")
		f:SetScript("OnEvent", function() error("boom") end)
		Mock.Fire("PLAYER_LOGIN")
		eq(#Mock.errors, 1)
		contains(Mock.errors[1].message, "boom")
		Mock.ClearErrors()
	end)

	it("Show and Hide run OnShow and OnHide; visibility follows the parent", function()
		local log = {}
		local parent = CreateFrame("Frame")
		local child = CreateFrame("Frame", nil, parent)
		child:SetScript("OnHide", function() log[#log + 1] = "hide" end)
		truthy(child:IsVisible())
		parent:Hide()
		falsy(child:IsVisible())
		truthy(child:IsShown())
		child:Hide()
		deepEq(log, { "hide" })
	end)

	it("an unknown widget method is nil, so calling it fails loudly", function()
		raises(function() CreateFrame("Frame"):NoSuchMethod() end, "NoSuchMethod")
	end)
end)

describe("chat", function()
	it("records accepted sends and returns Success", function()
		local result = C_ChatInfo.SendAddonMessage("AzGF", "hello", "GUILD")
		ne(result, Enum.SendAddonMessageResult.Success, "not in a guild: the client refuses")
		Mock.guild.Set({ name = "G" })
		eq(C_ChatInfo.SendAddonMessage("AzGF", "hello", "GUILD"), Enum.SendAddonMessageResult.Success)
		eq(#Mock.chat.sent, 1)
		eq(Mock.chat.sent[1].message, "hello")
	end)

	it("lockdown and forced results", function()
		Mock.guild.Set({ name = "G" })
		Mock.chat.lockdown = true
		truthy(C_ChatInfo.InChatMessagingLockdown())
		eq(C_ChatInfo.SendAddonMessage("AzGF", "x", "GUILD"), Enum.SendAddonMessageResult.AddOnMessageLockdown)
		Mock.chat.lockdown = false
		Mock.chat.QueueResults(Enum.SendAddonMessageResult.ChannelThrottle)
		eq(C_ChatInfo.SendAddonMessage("AzGF", "x", "GUILD"), Enum.SendAddonMessageResult.ChannelThrottle)
		eq(C_ChatInfo.SendAddonMessage("AzGF", "x", "GUILD"), Enum.SendAddonMessageResult.Success)
		eq(#Mock.chat.sent, 1, "a throttled send is not delivered")
		eq(#Mock.chat.attempts, 3)
	end)

	it("checks the arguments", function()
		local R = Enum.SendAddonMessageResult
		eq(C_ChatInfo.SendAddonMessage("", "x", "GUILD"), R.InvalidPrefix)
		eq(C_ChatInfo.SendAddonMessage("AzGF", string.rep("x", 300), "GUILD"), R.InvalidMessage)
		eq(C_ChatInfo.SendAddonMessage("AzGF", "x", "NOPE"), R.InvalidChatType)
		eq(C_ChatInfo.SendAddonMessage("AzGF", "x", "CHANNEL", 5), R.InvalidChannel)
	end)

	it("joins a channel after a frame and sends to it", function()
		JoinChannelByName("AzGuildFinder")
		Mock.Advance(0.1)
		local id = GetChannelName("AzGuildFinder")
		eq(id, 1)
		eq(C_ChatInfo.SendAddonMessage("AzGF", "ping", "CHANNEL", id), Enum.SendAddonMessageResult.Success)
		Mock.chat.channelsRejectAddon = true
		eq(C_ChatInfo.SendAddonMessage("AzGF", "ping", "CHANNEL", id), Enum.SendAddonMessageResult.InvalidChannel)
	end)

	it("CHAT_MSG_ADDON reaches handlers only for registered prefixes", function()
		local got = {}
		local f = CreateFrame("Frame")
		f:RegisterEvent("CHAT_MSG_ADDON")
		f:SetScript("OnEvent", function(_, _, prefix, text, channel, sender) got[#got + 1] = { prefix, text, channel, sender } end)
		falsy(Mock.chat.Receive("AzGFMock", "hi", "WHISPER", "Other-Realm"))
		eq(C_ChatInfo.RegisterAddonMessagePrefix("AzGFMock"), Enum.RegisterAddonMessagePrefixResult.Success)
		truthy(Mock.chat.Receive("AzGFMock", "hi", "WHISPER", "Other-Realm"))
		deepEq(got, { { "AzGFMock", "hi", "WHISPER", "Other-Realm" } })
	end)

	it("ChatThrottleLib (through AceComm) sends through C_ChatInfo as frames pass", function()
		Mock.guild.Set({ name = "G" })
		local AceComm = LibStub("AceComm-3.0")
		AceComm:SendCommMessage("AzGF", "queued", "GUILD")
		Mock.Advance(2)
		eq(#Mock.chat.SentWithPrefix("AzGF"), 1)
	end)
end)

describe("guild", function()
	it("has no guild by default", function()
		falsy(IsInGuild())
		eq(select("#", GetGuildInfo("player")), 1)
		eq(GetNumGuildMembers(), 0)
	end)

	it("reports the guild, the rank and the roster", function()
		Mock.guild.Set({
			name = "Night Watch", myRank = 1,
			members = {
				{ name = "Alice", level = 70, class = "MAGE", rank = 0 },
				{ name = "Bob", level = 12, class = "ROGUE", online = false, lastOnline = { 0, 1, 3, 4 } },
			},
		})
		local name, rankName, rankIndex = GetGuildInfo("player")
		eq(name, "Night Watch"); eq(rankName, "Officer"); eq(rankIndex, 1)
		local total, online = GetNumGuildMembers()
		eq(total, 3); eq(online, 2)
		eq((GetGuildRosterInfo(2)), "Alice")
		eq(select(5, GetGuildRosterInfo(2)), "Mage")
		eq(select(9, GetGuildRosterInfo(3)), false)
		deepEq({ GetGuildRosterLastOnline(3) }, { 0, 1, 3, 4 })
		isNil(GetGuildRosterLastOnline(2))
		truthy(C_GuildInfo.IsGuildOfficer())
		falsy(IsGuildLeader())
	end)

	it("changes of rank and guild fire the events and flip the role checks", function()
		local events = {}
		local f = CreateFrame("Frame")
		f:RegisterEvent("PLAYER_GUILD_UPDATE")
		f:SetScript("OnEvent", function(_, event) events[#events + 1] = event end)
		Mock.guild.Set({ name = "G", myRank = 0 })
		truthy(IsGuildLeader())
		Mock.guild.SetMyRank(3)
		falsy(IsGuildLeader()); falsy(C_GuildInfo.IsGuildOfficer())
		Mock.guild.Leave()
		falsy(IsInGuild())
		eq(#events, 3)
	end)

	it("GuildRoster answers on a later frame; Invite is recorded", function()
		local updates = 0
		local f = CreateFrame("Frame")
		f:RegisterEvent("GUILD_ROSTER_UPDATE")
		f:SetScript("OnEvent", function() updates = updates + 1 end)
		Mock.guild.Set({ name = "G" })
		updates = 0
		C_GuildInfo.GuildRoster()
		eq(updates, 0)
		Mock.Advance(0.1)
		eq(updates, 1)
		C_GuildInfo.Invite("Newbie")
		deepEq(Mock.guild.invites, { "Newbie" })
	end)
end)

