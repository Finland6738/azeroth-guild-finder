-- Listing (M2.1): Sanitize of the summary, detail and application records (SPEC-03 §2-§3, §6, §8).
local function L() return AzerothGuildFinder.Listing end
local function codec() return AzerothGuildFinder.Codec end
local KEY = "Firemaw|Alliance|Night Watch"
local OPTS = { maxLevel = 60 }

local function summary(extra)
	local t = { k = KEY, rev = 3, upd = 1700000000, first = 1690000000, own = "a1b2c3d4", sub = "Friendly raiders",
		lang = 3, lang1 = 1, tags = { 1, 2 }, pace = 2, days = 21, t0 = 1140, t1 = 1380, rec = 1, apps = true,
		want = { [0] = 8, [1] = 1, [5] = 2 }, newb = true, minL = 30, minI = 100,
		emb = { t = 1, e = 1, b = 2, g = 3, ec = 255, bc = 65280, gc = 16711680 }, bg = 4,
		st = { m = 40, a7 = 20, u7lo = 10, u7hi = 12, max = 5, cls = { [1] = 3, [8] = 2 } }, srev = 1700000000 }
	for k, v in pairs(extra or {}) do if v == "nil" then t[k] = nil else t[k] = v end end
	return t
end

local function hasIssue(issues, text)
	for _, i in ipairs(issues) do if i:find(text, 1, true) then return true end end
	return false
end

local function sum(extra) return (L().SanitizeSummary(summary(extra), OPTS)) end

describe("summary: a valid record", function()
	it("passes unchanged with no issue", function()
		local rec, issues = L().SanitizeSummary(summary(), OPTS)
		deepEq(rec, summary())
		deepEq(issues, {})
	end)
	it("returns a copy, not the input", function()
		local raw = summary()
		local rec = L().SanitizeSummary(raw, OPTS)
		ne(rec, raw)
		ne(rec.tags, raw.tags)
		ne(rec.want, raw.want)
	end)
	it("is idempotent", function()
		local raw = summary({ sub = "a|b ||c", tags = { 1, 1, 99, 3, 4, 5 }, want = { [4] = 15, [3] = 15 }, minL = 99, lang1 = "nil" })
		local once = L().SanitizeSummary(raw, OPTS)
		local twice, issues = L().SanitizeSummary(once, OPTS)
		deepEq(twice, once)
		deepEq(issues, {})
	end)
	it("drops unknown fields", function()
		local rec = sum({ evil = "x", st2 = {} })
		isNil(rec.evil)
		isNil(rec.st2)
	end)
	it("a minimal record is complete only with language, tags and pace", function()
		local rec = L().SanitizeSummary({ k = KEY, rev = 1 })
		deepEq(rec, { k = KEY, rev = 1 })
		falsy(L().IsComplete(rec))
		truthy(L().IsComplete(sum()))
		falsy(L().IsComplete(sum({ pace = "nil" })))
		falsy(L().IsComplete(sum({ tags = "nil" })))
		falsy(L().IsComplete(sum({ lang = "nil", lang1 = "nil" })))
		falsy(L().IsComplete(nil))
	end)
end)

describe("summary: the whole record is rejected", function()
	local cases = {
		{ "not a table", "x" },
		{ "no k", { rev = 1 } },
		{ "k not a string", { k = 5, rev = 1 } },
		{ "empty k", { k = "", rev = 1 } },
		{ "k without parts", { k = "Firemaw", rev = 1 } },
		{ "k with one pipe", { k = "Firemaw|Alliance", rev = 1 } },
		{ "k with an empty guild", { k = "Firemaw|Alliance|", rev = 1 } },
		{ "k with an empty realm", { k = "|Alliance|Guild", rev = 1 } },
		{ "k with a bad faction", { k = "Firemaw|Neutral|Guild", rev = 1 } },
		{ "k with a pipe in the guild name", { k = "Firemaw|Alliance|Gu|ild", rev = 1 } },
		{ "k with a control character", { k = "Firemaw|Alliance|Gu\nild", rev = 1 } },
		{ "k over 80 characters", { k = "Firemaw|Alliance|" .. string.rep("x", 64), rev = 1 } },
		{ "no rev", { k = KEY } },
		{ "rev 0", { k = KEY, rev = 0 } },
		{ "rev negative", { k = KEY, rev = -1 } },
		{ "rev a string", { k = KEY, rev = "3" } },
		{ "rev fractional", { k = KEY, rev = 1.5 } },
		{ "rev NaN", { k = KEY, rev = 0 / 0 } },
		{ "rev infinite", { k = KEY, rev = math.huge } },
	}
	for _, c in ipairs(cases) do
		it(c[1], function()
			local rec, issues = L().SanitizeSummary(c[2])
			isNil(rec)
			truthy(#issues >= 1)
		end)
	end
	it("accepts a key of exactly 80 characters and rejects 81", function()
		local base = "Firemaw|Alliance|"
		truthy(L().SanitizeSummary({ k = base .. string.rep("x", 80 - #base), rev = 1 }))
		isNil(L().SanitizeSummary({ k = base .. string.rep("x", 81 - #base), rev = 1 }))
	end)
	it("counts the key in UTF-8 characters", function()
		local base = "Firemaw|Alliance|"
		truthy(L().SanitizeSummary({ k = base .. string.rep("é", 80 - #base), rev = 1 }))
		isNil(L().SanitizeSummary({ k = base .. string.rep("é", 81 - #base), rev = 1 }))
	end)
end)

describe("summary: numbers and enums", function()
	local function one(field, value, opts)
		local rec, issues = L().SanitizeSummary(summary({ [field] = value }), opts or OPTS)
		return rec, issues
	end
	it("pace accepts 1, 2, 3 only", function()
		for _, v in ipairs({ 1, 2, 3 }) do eq(one("pace", v).pace, v) end
		for _, v in ipairs({ 0, 4, -1, 2.5, "2", true }) do
			local rec, issues = one("pace", v)
			isNil(rec.pace, tostring(v))
			truthy(hasIssue(issues, "pace"))
		end
	end)
	it("rec accepts 0, 1, 2 only", function()
		for _, v in ipairs({ 0, 1, 2 }) do eq(one("rec", v).rec, v) end
		for _, v in ipairs({ 3, -1, 1.5, "1" }) do isNil(one("rec", v).rec) end
	end)
	it("days is a 7-bit mask 0..127", function()
		eq(one("days", 0).days, 0)
		eq(one("days", 127).days, 127)
		isNil(one("days", 128).days)
		isNil(one("days", -1).days)
	end)
	it("t0 and t1 are minutes 0..1439 and travel together", function()
		local r = sum({ t0 = 0, t1 = 1439 })
		eq(r.t0, 0)
		eq(r.t1, 1439)
		local bad = sum({ t0 = 1440 })
		isNil(bad.t0)
		isNil(bad.t1)
		bad = sum({ t1 = "nil" })
		isNil(bad.t0)
		isNil(bad.t1)
		local same = sum({ t0 = 600, t1 = 600 })
		eq(same.t0, 600)
		eq(same.t1, 600)
	end)
	it("minL is 1..max level", function()
		eq(one("minL", 1).minL, 1)
		eq(one("minL", 60).minL, 60)
		isNil(one("minL", 0).minL)
		isNil(one("minL", 61).minL)
		eq(one("minL", 70, { maxLevel = 80 }).minL, 70)
	end)
	it("minL uses the client's maximum level when none is given", function()
		local max = AzerothGuildFinder.Compat.Player.MaxLevel() or 60
		eq(L().SanitizeSummary(summary({ minL = max })).minL, max)
		isNil(L().SanitizeSummary(summary({ minL = max + 1 })).minL)
	end)
	it("minI is 0..999", function()
		eq(one("minI", 0).minI, 0)
		eq(one("minI", 999).minI, 999)
		isNil(one("minI", 1000).minI)
		isNil(one("minI", -1).minI)
	end)
	it("bg is a positive index", function()
		eq(one("bg", 1).bg, 1)
		isNil(one("bg", 0).bg)
		isNil(one("bg", 256).bg)
	end)
	it("apps and newb must be booleans", function()
		eq(one("apps", false).apps, false)
		isNil(one("apps", 1).apps)
		isNil(one("newb", "yes").newb)
	end)
	it("own is 8 hexadecimal characters, lower-cased", function()
		eq(one("own", "A1B2C3D4").own, "a1b2c3d4")
		isNil(one("own", "a1b2c3").own)
		isNil(one("own", "a1b2c3dg").own)
		isNil(one("own", 12345678).own)
	end)
	it("upd, first and srev are epochs", function()
		isNil(one("upd", -5).upd)
		isNil(one("first", "x").first)
		isNil(one("srev", 1.5).srev)
		eq(one("upd", 0).upd, 0)
	end)
	it("a wrong type never raises", function()
		for _, field in ipairs({ "sub", "lang", "lang1", "tags", "pace", "days", "t0", "rec", "want", "minL", "minI", "emb", "bg", "st", "own", "apps" }) do
			for _, v in ipairs({ true, 5, "text", {}, function() end }) do
				local ok = pcall(L().SanitizeSummary, summary({ [field] = v }), OPTS)
				truthy(ok, field .. " " .. type(v))
			end
		end
	end)
end)

describe("summary: languages", function()
	it("keeps lang1 and puts its bit in the mask", function()
		local r = sum({ lang = 4, lang1 = 1 })
		eq(r.lang1, 1)
		eq(r.lang, 5)
	end)
	it("takes the lowest bit of the mask as main when lang1 is missing or invalid", function()
		eq(sum({ lang = 12, lang1 = "nil" }).lang1, 3)
		eq(sum({ lang = 12, lang1 = 0 }).lang1, 3)
	end)
	it("builds the mask from lang1 alone", function()
		local r = sum({ lang = "nil", lang1 = 5 })
		eq(r.lang, 16)
		eq(r.lang1, 5)
	end)
	it("removes bits of unknown languages", function()
		local r, issues = L().SanitizeSummary(summary({ lang = 512 + 3, lang1 = 1 }), OPTS)
		eq(r.lang, 3)
		truthy(hasIssue(issues, "lang"))
	end)
	it("drops an invalid mask", function()
		eq(sum({ lang = -1, lang1 = 2 }).lang, 2)
		isNil(sum({ lang = 0, lang1 = 10 }).lang1)
	end)
end)

describe("summary: tags", function()
	local function tags(v) return sum({ tags = v }) end
	it("keeps 1 to 3 activities in order", function()
		deepEq(tags({ 5 }).tags, { 5 })
		deepEq(tags({ 13, 1, 7 }).tags, { 13, 1, 7 })
	end)
	it("cuts to three", function()
		local r, issues = L().SanitizeSummary(summary({ tags = { 1, 2, 3, 4 } }), OPTS)
		deepEq(r.tags, { 1, 2, 3 })
		truthy(hasIssue(issues, "more than 3"))
	end)
	it("drops repeated and invalid activities", function()
		deepEq(tags({ 2, 2, 99, 0, 3, 2 }).tags, { 2, 3 })
		deepEq(tags({ "1", 1.5, 4 }).tags, { 4 })
	end)
	it("an empty or fully invalid list leaves the field out", function()
		isNil(tags({}).tags)
		isNil(tags({ 14, 0 }).tags)
		isNil(tags("1,2").tags)
	end)
	it("a repeated activity does not use a slot", function()
		deepEq(tags({ 1, 1, 2, 3 }).tags, { 1, 2, 3 })
	end)
end)

describe("summary: want", function()
	local function want(v) return sum({ want = v }).want end
	it("filters the roles a class cannot play", function()
		deepEq(want({ [3] = 15, [4] = 15, [5] = 15, [1] = 15 }), { [3] = 8, [4] = 4, [5] = 10, [1] = 5 })
	end)
	it("drops a class left with no valid role", function()
		deepEq(want({ [3] = 1 + 2 + 4, [8] = 8 }), { [8] = 8 })
		isNil(want({ [3] = 1 }))
	end)
	it("class 0 means any class and keeps the mask", function()
		deepEq(want({ [0] = 15 }), { [0] = 15 })
	end)
	it("drops invalid keys and masks", function()
		deepEq(want({ [-1] = 1, [1.5] = 1, x = 1, [1] = "4", [8] = 8 }), { [8] = 8 })
		isNil(want({ [1] = 0 }))
	end)
	it("an unknown class keeps every role", function() deepEq(want({ [99] = 15 }), { [99] = 15 }) end)
	it("keeps at most 30 entries, lowest ids first", function()
		local big = {}
		for i = 1, 40 do big[100 + i] = 8 end
		local r, issues = L().SanitizeSummary(summary({ want = big }), OPTS)
		local n = 0
		for id in pairs(r.want) do n = n + 1 truthy(id <= 130) end
		eq(n, 30)
		truthy(hasIssue(issues, "30"))
	end)
	it("an empty or non-table want leaves the field out", function()
		isNil(want({}))
		isNil(want("x"))
	end)
end)

