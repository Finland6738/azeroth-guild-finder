describe("text rules (SPEC-03 §6)", function()
	local function sub(s) return sum({ sub = s }).sub end
	it("limits sub to 60 characters", function()
		eq(sub(string.rep("a", 60)), string.rep("a", 60))
		eq(sub(string.rep("a", 61)), string.rep("a", 60))
	end)
	it("counts UTF-8 characters, not bytes", function()
		local s = string.rep("é", 60)
		eq(#s, 120)
		eq(sub(s), s)
		eq(sub(string.rep("é", 61)), s)
		eq(sub(string.rep("日", 70)), string.rep("日", 60))
	end)
	it("never cuts a multibyte character in half", function()
		local r = sub(string.rep("a", 59) .. "é" .. "tail")
		eq(r, string.rep("a", 59) .. "é")
		eq(AzerothGuildFinder.Normalize.Utf8Len(r), 60)
	end)
	it("escapes | as ||", function()
		eq(sub("a|b"), "a||b")
		eq(sub("|cffff0000red|r"), "||cffff0000red||r")
		eq(sub("|Hitem:1|h[x]|h"), "||Hitem:1||h[x]||h")
	end)
	it("is stable on an already escaped text", function()
		eq(sub("a||b"), "a||b")
		eq(sub("a|||b"), "a||||b")
		eq(sub(sub("a|b|||c")), sub("a|b|||c"))
	end)
	it("leaves no odd run of pipes when the cut falls inside an escape", function()
		local r = sub(string.rep("a", 59) .. "|b")
		eq(r, string.rep("a", 59))
		local r2 = sub(string.rep("a", 58) .. "|b")
		eq(r2, string.rep("a", 58) .. "||")
	end)
	it("removes control characters, newline too", function()
		eq(sub("a\0b\1c\9d\10e\13f\27g\127h"), "abcdefgh")
		eq(sub("x\194\128y\194\159z"), "xyz")
	end)
	it("trims the ends", function() eq(sub("  hi  "), "hi") end)
	it("leaves out an empty text", function()
		isNil(sub(""))
		isNil(sub("  \n "))
		isNil(sub(7))
	end)
	it("keeps accents and symbols", function() eq(sub("Ordine del Drago — è così"), "Ordine del Drago — è così") end)
end)

describe("detail", function()
	local function detail(extra)
		local t = { k = KEY, rev = 3, desc = "We raid on Tuesday.", disc = "abc123", cont = { "Gm-Firemaw" }, note = "Voice chat required" }
		for k, v in pairs(extra or {}) do if v == "nil" then t[k] = nil else t[k] = v end end
		return t
	end
	local function det(extra) return (L().SanitizeDetail(detail(extra))) end
	it("passes a valid record unchanged", function()
		local rec, issues = L().SanitizeDetail(detail())
		deepEq(rec, detail())
		deepEq(issues, {})
	end)
	it("rejects a record without a valid k or rev", function()
		isNil(det({ k = "x" }))
		isNil(det({ rev = 0 }))
		isNil(L().SanitizeDetail(nil))
	end)
	it("limits desc to 500 characters", function()
		eq(#det({ desc = string.rep("a", 500) }).desc, 500)
		eq(#det({ desc = string.rep("a", 501) }).desc, 500)
		eq(AzerothGuildFinder.Normalize.Utf8Len(det({ desc = string.rep("è", 501) }).desc), 500)
	end)
	it("keeps newlines in desc, at most 12 lines", function()
		local twelve = {}
		for i = 1, 12 do twelve[i] = "line" .. i end
		local text = table.concat(twelve, "\n")
		eq(det({ desc = text }).desc, text)
		eq(det({ desc = text .. "\nline13\nline14" }).desc, text)
	end)
	it("turns CRLF into a newline and drops other controls in desc", function()
		eq(det({ desc = "a\r\nb\1c\ttd" }).desc, "a\nbctd")
	end)
	it("counts blank lines towards the 12", function()
		isNil(det({ desc = string.rep("\n", 20) .. "x" }).desc)
	end)
	it("escapes pipes in desc and note", function()
		local r = det({ desc = "|cffff0000x|r", note = "a|b" })
		eq(r.desc, "||cffff0000x||r")
		eq(r.note, "a||b")
	end)
	it("limits note to 120 characters and strips newlines", function()
		eq(#det({ note = string.rep("n", 121) }).note, 120)
		eq(det({ note = "a\nb" }).note, "ab")
	end)
	it("is idempotent", function()
		local once = det({ desc = "a|b\n\n|c", note = "x|y", disc = "https://discord.gg/abc" })
		local twice, issues = L().SanitizeDetail(once)
		deepEq(twice, once)
		deepEq(issues, {})
	end)
	it("keeps at most 3 unique contact names", function()
		deepEq(det({ cont = { "A-R", "a-r", "B-R", "C-R", "D-R" } }).cont, { "A-R", "B-R", "C-R" })
	end)
	it("drops invalid contact names", function()
		deepEq(det({ cont = { "", 5, "a|b", "Good\n" } }).cont, { "Good" })
		isNil(det({ cont = { 1 } }).cont)
		isNil(det({ cont = "A" }).cont)
		isNil(det({ cont = { string.rep("x", 49) } }).cont)
	end)
end)

describe("Discord", function()
	local function code(s) return (L().ExtractDiscordCode(s)) end
	it("accepts a bare code", function()
		eq(code("abc123"), "abc123")
		eq(code("Ab-C"), "Ab-C")
		eq(code("ab"), "ab")
		eq(code(string.rep("a", 32)), string.rep("a", 32))
	end)
	it("rejects a code that is too short or too long", function()
		isNil(code("a"))
		isNil(code(string.rep("a", 33)))
		isNil(code(""))
	end)
	it("rejects bad characters", function()
		isNil(code("ab_cd"))
		isNil(code("ab cd"))
		isNil(code("ab!"))
		isNil(code("é1234"))
	end)
	it("extracts the code from full links", function()
		eq(code("discord.gg/abc"), "abc")
		eq(code("https://discord.gg/abc"), "abc")
		eq(code("http://discord.gg/abc"), "abc")
		eq(code("https://www.discord.gg/abc"), "abc")
		eq(code("discord.com/invite/abc"), "abc")
		eq(code("https://discord.com/invite/AbC-9"), "AbC-9")
		eq(code("https://discordapp.com/invite/abc"), "abc")
		eq(code("HTTPS://DISCORD.GG/abc"), "abc")
	end)
	it("ignores a trailing slash, query, fragment and spaces", function()
		eq(code("https://discord.gg/abc/"), "abc")
		eq(code("https://discord.gg/abc?event=1"), "abc")
		eq(code("  https://discord.gg/abc#x  "), "abc")
	end)
	it("rejects other sites and malformed links", function()
		isNil(code("https://example.com/abc"))
		isNil(code("https://discord.gg/"))
		isNil(code("https://discord.gg/a"))
		isNil(code("https://discord.gg/bad_code"))
		isNil(code("discord.gg"))
		isNil(code(nil))
		isNil(code(42))
	end)
	it("disc in a detail record is reduced to the code", function()
		eq(L().SanitizeDetail({ k = KEY, rev = 1, disc = "https://discord.gg/abc" }).disc, "abc")
		local r, issues = L().SanitizeDetail({ k = KEY, rev = 1, disc = "https://evil.example/x" })
		isNil(r.disc)
		truthy(hasIssue(issues, "disc"))
		isNil(L().SanitizeDetail({ k = KEY, rev = 1, disc = 5 }).disc)
	end)
	it("IsValidDiscordCode follows ^[A-Za-z0-9-]{2,32}$", function()
		truthy(L().IsValidDiscordCode("a-"))
		falsy(L().IsValidDiscordCode("a"))
		falsy(L().IsValidDiscordCode("a.b"))
		falsy(L().IsValidDiscordCode(nil))
	end)
end)

