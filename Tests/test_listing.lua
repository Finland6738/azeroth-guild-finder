describe("application (SPEC-03 §8)", function()
	local function app(extra)
		local t = { id = "a1b2c3d4", k = KEY, who = "Thrall-Firemaw", cls = 8, race = 2, lvl = 40, ilvl = 120, roles = 8,
			at = 1700000000, state = "sent", stateRev = 1, by = "Gm-Firemaw" }
		for k, v in pairs(extra or {}) do if v == "nil" then t[k] = nil else t[k] = v end end
		return t
	end
	local function ap(extra) return (L().SanitizeApplication(app(extra), OPTS)) end
	it("passes a valid record", function()
		local rec, issues = L().SanitizeApplication(app(), OPTS)
		deepEq(rec, app())
		deepEq(issues, {})
	end)
	it("rejects without a valid id or k", function()
		isNil(ap({ id = "a1b2c3" }))
		isNil(ap({ id = "zzzzzzzz" }))
		isNil(ap({ id = "nil" }))
		isNil(ap({ k = "nope" }))
		isNil(L().SanitizeApplication(nil))
	end)
	it("restricts roles to the class", function()
		eq(ap({ cls = 4, roles = 15 }).roles, 4)         -- Rogue
		eq(ap({ cls = 1, roles = 1 + 4 + 8 }).roles, 5)  -- Warrior
		isNil(ap({ cls = 3, roles = 1 }).roles)          -- Hunter cannot tank
		eq(ap({ cls = 11, roles = 15 }).roles, 15)       -- Druid
	end)
	it("roles are optional and a missing class only limits the mask range", function()
		isNil(ap({ roles = "nil" }).roles)
		eq(ap({ cls = "nil", roles = 9 }).roles, 9)
		isNil(ap({ roles = "tank" }).roles)
	end)
	it("accepts the six states only", function()
		for _, s in ipairs({ "sent", "received", "accepted", "declined", "withdrawn", "expired" }) do
			eq(ap({ state = s }).state, s)
		end
		isNil(ap({ state = "pending" }).state)
		isNil(ap({ state = 1 }).state)
	end)
	it("validates who and by as Name-Realm", function()
		isNil(ap({ who = "Thrall" }).who)
		isNil(ap({ who = "-Firemaw" }).who)
		isNil(ap({ who = "Thr|all-Firemaw" }).who)
		isNil(ap({ who = "Thrall-Fire\nmaw" }).who)
		isNil(ap({ by = "x" }).by)
		eq(ap({ who = "Thrall-Fire Maw" }).who, "Thrall-Fire Maw")
	end)
	it("bounds the numbers", function()
		isNil(ap({ lvl = 0 }).lvl)
		isNil(ap({ lvl = 61 }).lvl)
		isNil(ap({ ilvl = 1000 }).ilvl)
		eq(ap({ ilvl = 0 }).ilvl, 0)
		isNil(ap({ cls = 0 }).cls)
		isNil(ap({ race = 1.5 }).race)
		isNil(ap({ at = -1 }).at)
		isNil(ap({ stateRev = -1 }).stateRev)
	end)
	it("lower-cases the id and is idempotent", function()
		eq(ap({ id = "A1B2C3D4" }).id, "a1b2c3d4")
		local once = ap({ cls = 4, roles = 15 })
		deepEq((L().SanitizeApplication(once, OPTS)), once)
	end)
end)

describe("round trip through the codec", function()
	local function through(t, fields)
		local payload, err = codec():Encode(t, fields)
		truthy(payload, err)
		local msg, reason = codec():Decode(payload)
		truthy(msg, reason)
		return msg
	end
	it("a sanitized summary survives ANN unchanged", function()
		local rec = sum({ sub = "pipe | and é" })
		local back, issues = L().SanitizeSummary(through("ANN", rec), OPTS)
		deepEq(back, rec)
		deepEq(issues, {})
	end)
	it("a summary in a CAT batch survives", function()
		local rec = sum()
		local msg = through("CAT", { nonce = 5, items = { rec } })
		deepEq((L().SanitizeSummary(msg.items[1], OPTS)), rec)
	end)
	it("a detail survives DET and a full record survives GLIST", function()
		local d = L().SanitizeDetail({ k = KEY, rev = 2, desc = "Line one\nLine || two", disc = "abc", cont = { "A-B", "C-D" }, note = "n" })
		deepEq((L().SanitizeDetail(through("DET", d))), d)
		local full = L().SanitizeFull(summary({ desc = "d", disc = "xyz" }), OPTS)
		deepEq((L().SanitizeFull(through("GLIST", full), OPTS)), full)
	end)
	it("a maximum-size summary and detail can be encoded", function()
		local big = {}
		for i = 1, 30 do big[i] = (i % 15) + 1 end
		local rec = sum({ sub = string.rep("é", 60), want = big })
		truthy(codec():Encode("ANN", rec))
		local d = L().SanitizeDetail({ k = KEY, rev = 1, desc = string.rep("word ", 100), note = string.rep("n", 120) })
		truthy(codec():Encode("DET", d))
	end)
	it("a hostile message is cleaned after decoding", function()
		local msg = through("ANN", { k = KEY, rev = 1, sub = "|cffff0000x|r\1", tags = { 99, 1, 1 }, pace = 9, want = { [3] = 15 }, extra = 1 })
		local rec = L().SanitizeSummary(msg)
		eq(rec.sub, "||cffff0000x||r")
		deepEq(rec.tags, { 1 })
		isNil(rec.pace)
		deepEq(rec.want, { [3] = 8 })
		isNil(rec.extra)
		isNil(rec.v)
		isNil(rec.t)
	end)
end)
