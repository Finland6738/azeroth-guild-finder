describe("ChipGroup", function()
	local items = {
		{ key = 1, text = "Raids" }, { key = 2, text = "Dungeons" }, { key = 3, text = "Leveling" },
		{ key = 4, text = "Battlegrounds" }, { key = 5, text = "Roleplay" },
	}

	it("reports the selected keys in item order", function()
		local last
		local g = W().ChipGroup(parent(), items, { width = 400, onChange = function(keys) last = keys end })
		click(g.chips[3]); click(g.chips[1])
		deepEq(last, { 1, 3 })
		deepEq(g:GetSelected(), { 1, 3 })
	end)

	it("wraps the chips onto new rows inside its width", function()
		local g = W().ChipGroup(parent(), items, { width = 200 })
		local rows = {}
		for _, key in ipairs(g.order) do
			local _, _, _, x, y = g.chips[key]:GetPoint(1)
			rows[y] = true
			truthy(x + g.chips[key]:GetWidth() <= 200 or x == 0, "chip " .. key .. " inside the width")
		end
		local n = 0
		for _ in pairs(rows) do n = n + 1 end
		truthy(n > 1, "more than one row")
		truthy(g:GetHeight() >= 30 * n)
	end)

	it("with max, a chip over the limit is refused and onLimit is told", function()
		local limit, last
		local g = W().ChipGroup(parent(), items, { width = 600, max = 2, onLimit = function(m) limit = m end,
			onChange = function(keys) last = keys end })
		click(g.chips[1]); click(g.chips[2]); click(g.chips[3])
		eq(limit, 2)
		deepEq(g:GetSelected(), { 1, 2 })
		falsy(g.chips[3]:GetSelected())
		deepEq(last, { 1, 2 })
	end)

	it("single choice: selecting one clears the others, with one change event", function()
		local events = 0
		local g = W().ChipGroup(parent(), items, { width = 600, multi = false, onChange = function() events = events + 1 end })
		click(g.chips[1])
		click(g.chips[2])
		deepEq(g:GetSelected(), { 2 })
		eq(events, 2)
	end)

	it("SetSelected and Clear set the state, silently when asked", function()
		local events = 0
		local g = W().ChipGroup(parent(), items, { width = 600, onChange = function() events = events + 1 end })
		g:SetSelected({ 2, 4 })
		deepEq(g:GetSelected(), { 2, 4 })
		eq(events, 1)
		g:Clear(true)
		deepEq(g:GetSelected(), {})
		eq(events, 1)
	end)
end)

