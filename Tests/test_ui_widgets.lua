describe("Snackbar", function()
	it("shows a message and hides it after the time", function()
		truthy(W().Snackbar.Show("Saved"))
		truthy(W().Snackbar.IsShown())
		eq(W().Snackbar.Current(), "Saved")
		truthy(W().Snackbar.Frame():IsShown())
		Mock.Advance(3.9)
		truthy(W().Snackbar.IsShown())
		Mock.Advance(0.2)
		falsy(W().Snackbar.IsShown())
		falsy(W().Snackbar.Frame():IsShown())
	end)

	it("ignores empty text", function()
		falsy(W().Snackbar.Show(""))
		falsy(W().Snackbar.Show(nil))
		falsy(W().Snackbar.IsShown())
	end)

	it("queues messages and shows them one after the other", function()
		W().Snackbar.Show("One", { seconds = 2 })
		W().Snackbar.Show("Two", { seconds = 2 })
		W().Snackbar.Show("Three", { seconds = 2 })
		eq(W().Snackbar.Current(), "One")
		eq(W().Snackbar.Pending(), 2)
		Mock.Advance(2.1)
		eq(W().Snackbar.Current(), "Two")
		Mock.Advance(2.1)
		eq(W().Snackbar.Current(), "Three")
		Mock.Advance(2.1)
		falsy(W().Snackbar.IsShown())
		eq(W().Snackbar.Pending(), 0)
	end)

	it("a waiting message with the same key is replaced", function()
		W().Snackbar.Show("A")
		W().Snackbar.Show("old", { key = "k" })
		W().Snackbar.Show("new", { key = "k" })
		eq(W().Snackbar.Pending(), 1)
		Mock.Advance(4.1)
		eq(W().Snackbar.Current(), "new")
	end)

	it("the same key as the message on screen refreshes it and restarts the time", function()
		W().Snackbar.Show("Copy", { key = "c" })
		Mock.Advance(3)
		W().Snackbar.Show("Copy again", { key = "c" })
		eq(W().Snackbar.Pending(), 0)
		eq(W().Snackbar.Current(), "Copy again")
		Mock.Advance(2)
		truthy(W().Snackbar.IsShown(), "the old timer did not hide the new message")
		Mock.Advance(2.1)
		falsy(W().Snackbar.IsShown())
	end)

	it("keeps at most five waiting, dropping the oldest", function()
		W().Snackbar.Show("first")
		for i = 1, 7 do W().Snackbar.Show("w" .. i) end
		eq(W().Snackbar.Pending(), 5)
		W().Snackbar.Dismiss()
		eq(W().Snackbar.Current(), "w3")
	end)

	it("an action runs its handler and closes the message", function()
		local undone = 0
		W().Snackbar.Show("Listing removed", { action = { text = "Undo", onClick = function() undone = undone + 1 end } })
		local frame = W().Snackbar.Frame()
		truthy(frame.action:IsShown())
		eq(frame.action.text:GetText(), "Undo")
		click(frame.action)
		eq(undone, 1)
		falsy(W().Snackbar.IsShown())
	end)

	it("a message without an action hides the action button; a tap dismisses it", function()
		W().Snackbar.Show("Plain")
		falsy(W().Snackbar.Frame().action:IsShown())
		Mock.RunScript(W().Snackbar.Frame(), "OnMouseUp")
		falsy(W().Snackbar.IsShown())
	end)

	it("sits at the bottom of the frame it is anchored to", function()
		local anchor = parent()
		W().Snackbar.SetAnchor(anchor)
		W().Snackbar.Show("Here")
		local point, rel = W().Snackbar.Frame():GetPoint(1)
		eq(point, "BOTTOM")
		eq(rel, anchor)
	end)
end)
