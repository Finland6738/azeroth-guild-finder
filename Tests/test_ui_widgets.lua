describe("Skin tokens", function()
	it("reads hex colours", function()
		local r, g, b = Skin().Hex("#f6d6a6")
		near(r, 246 / 255); near(g, 214 / 255); near(b, 166 / 255)
		eq(select("#", Skin().Hex("f6d6a6")), 3, "the # is optional")
		isNil(Skin().Hex("#xyz"))
		isNil(Skin().Hex(12))
		isNil(Skin().Hex("#f6d6a"))
	end)

	it("writes colours back as hex", function()
		eq(Skin().ToHex(1, 0, 0), "ff0000")
		eq(Skin().ToHex(0.5, 2, -1), "80ff00")
		eq(Skin().ToHex(Skin().Hex("#2e7d32")), "2e7d32")
	end)

	it("every colour token is a valid hex colour", function()
		for name, hex in pairs(Skin().COLORS) do notNil(Skin().Hex(hex), name) end
		for kind, k in pairs(Skin().KINDS) do
			notNil(Skin().Hex(k.text), kind)
			if k.fill then notNil(Skin().Hex(k.fill), kind) end
		end
		for kind, k in pairs(Skin().TAGS) do notNil(Skin().Hex(k.bg), kind); notNil(Skin().Hex(k.text), kind) end
	end)

	it("an unknown colour is white", function()
		local r, g, b, a = Skin().Color("nope")
		eq(r, 1); eq(g, 1); eq(b, 1); eq(a, 1)
	end)

	it("no style of the type scale is below 12 px once the fonts are made", function()
		Skin().CreateFonts()
		for style in pairs(Skin().STYLES) do
			local _, size = Skin().Font(style):GetFont()
			truthy(size >= 12, style .. " " .. tostring(size))
		end
	end)

	it("Roboto for the interface, Roboto Mono only for codes, links, times and commands", function()
		for style, s in pairs(Skin().STYLES) do
			if style == "mono" or style == "monoM" then eq(s.family, "RobotoMono", style) else eq(s.family, "Roboto", style) end
		end
		contains(Skin().FontFile("headline"), "Media\\Fonts\\Roboto-Bold.ttf")
		contains(Skin().FontFile("mono"), "Media\\Fonts\\RobotoMono-Regular.ttf")
	end)

	it("makes one font object per style, named AGF_<Style>", function()
		Skin().CreateFonts()
		notNil(_G.AGF_Headline)
		notNil(_G.AGF_Body)
		eq(Skin().Font("headline"), _G.AGF_Headline)
		isNil(Skin().Font("nonsense"))
	end)

	it("uses a bundled font when it loads and the client's font when it does not", function()
		T.boot(function()
			Mock.missingFonts["Interface\\AddOns\\AzerothGuildFinder\\Media\\Fonts\\Roboto-Bold.ttf"] = true
		end)
		Skin().CreateFonts()
		eq(Skin().fontSource.headline, "fallback")
		eq(Skin().fontSource.body, "bundled")
		local path = Skin().Font("headline"):GetFont()
		eq(path, "Fonts\\FRIZQT__.TTF")
		contains(Skin().Font("body"):GetFont(), "Roboto-Regular.ttf")
		contains(table.concat(AzerothGuildFinder.Skin:DebugLines(), " "), "on the client's font")
	end)
end)

