-- M3.5: the Recruitment, Requirements and Contact steps of the listing editor. First the rules without frames (EditorModel: the
-- class x role grid and the `want` map of SPEC-03, the faction filter, the status; the requirement limits; the Discord input;
-- the contacts picked from the guild roster), then the pages on the mock client (UI/EditorSteps.lua) and the checklist.
-- The mock player is "Testchar", a Horde Warrior, on "Test Realm"; the guild is "Iron Wolves".

local GUILD = "Iron Wolves"
local KEY = "TestRealm|Horde|" .. GUILD

local function A() return AzerothGuildFinder end
local function M() return A().EditorModel end
local function E() return A().Enums end
local function editor() return A().Editor end
local function OL() return A().OwnListing end
local function main() return A().Main end
local L = setmetatable({}, { __index = function(_, key) return LibStub("AceLocale-3.0"):GetLocale("AzerothGuildFinder")[key] end })

local TANK, HEALER, MELEE, RANGED = 1, 2, 4, 8
local WARRIOR, PALADIN, HUNTER, ROGUE, PRIEST, SHAMAN, MAGE, WARLOCK, DRUID = 1, 2, 3, 4, 5, 7, 8, 9, 11

local function ctx(extra)
	local t = { L = L, key = KEY, leader = true, canEdit = true, status = "none", wait = 0, changed = true }
	for k, v in pairs(extra or {}) do t[k] = v end
	return t
end
local function states(view)
	local out = {}
	for _, it in ipairs(view.items) do out[it.id] = it.state end
	return out
end
local function ids(list)
	local out = {}
	for i, c in ipairs(list) do out[i] = c.id end
	return out
end

describe("the grid: which classes and roles", function()
	it("offers the classes of the Horde, not the Paladin", function()
		deepEq(ids(M().GridClasses("Horde")), { WARRIOR, HUNTER, ROGUE, PRIEST, SHAMAN, MAGE, WARLOCK, DRUID })
	end)

	it("offers the classes of the Alliance, not the Shaman", function()
		deepEq(ids(M().GridClasses("Alliance")), { WARRIOR, PALADIN, HUNTER, ROGUE, PRIEST, MAGE, WARLOCK, DRUID })
	end)

	it("an unknown faction restricts nothing, and each row says the class file and the roles it can play", function()
		eq(#M().GridClasses(nil), 9)
		local rows = M().GridClasses("Horde")
		eq(rows[1].file, "WARRIOR")
		eq(rows[1].valid, TANK + MELEE)
		eq(rows[#rows].file, "DRUID")
		eq(rows[#rows].valid, 15)
	end)

	it("impossible pairs are blocked, possible ones are on or off, and Any class never blocks", function()
		eq(M().Cell({}, WARRIOR, HEALER), "blocked")
		eq(M().Cell({}, HUNTER, TANK), "blocked")
		eq(M().Cell({}, ROGUE, RANGED), "blocked")
		eq(M().Cell({}, MAGE, MELEE), "blocked")
		eq(M().Cell({}, WARRIOR, TANK), "off")
		eq(M().Cell({ [WARRIOR] = TANK }, WARRIOR, TANK), "on")
		eq(M().Cell({ [WARRIOR] = TANK }, WARRIOR, MELEE), "off")
		for _, bit in ipairs({ TANK, HEALER, MELEE, RANGED }) do
			eq(M().Cell({}, 0, bit), "off")
			eq(M().Cell({}, DRUID, bit), "off", "a Druid can play every role")
		end
		eq(M().Cell({ [0] = RANGED }, 0, RANGED), "on")
	end)
end)

describe("the grid makes the `want` map of SPEC-03", function()
	it("ticking roles of a class adds their bits (Tank 1, Healer 2, Melee 4, Ranged 8)", function()
		local want, result = M().ToggleRole({}, WARRIOR, TANK, "Horde")
		eq(result, "added")
		deepEq(want, { [WARRIOR] = 1 })
		want, result = M().ToggleRole(want, WARRIOR, MELEE, "Horde")
		eq(result, "added")
		deepEq(want, { [WARRIOR] = 5 })
		want = M().ToggleRole(want, DRUID, HEALER, "Horde")
		want = M().ToggleRole(want, DRUID, RANGED, "Horde")
		deepEq(want, { [WARRIOR] = 5, [DRUID] = 10 })
	end)

	it("unticking removes the bit, and a class with no role left leaves the map", function()
		local want = { [WARRIOR] = 5, [PRIEST] = 2 }
		local out, result = M().ToggleRole(want, WARRIOR, TANK, "Horde")
		eq(result, "removed")
		deepEq(out, { [WARRIOR] = 4, [PRIEST] = 2 })
		out = M().ToggleRole(out, WARRIOR, MELEE, "Horde")
		deepEq(out, { [PRIEST] = 2 })
		isNil(out[WARRIOR])
	end)

	it("does not change the map it is given", function()
		local want = { [WARRIOR] = 1 }
		M().ToggleRole(want, WARRIOR, MELEE, "Horde")
		deepEq(want, { [WARRIOR] = 1 })
	end)

	it("an impossible pair is refused and nothing changes", function()
		local want, result = M().ToggleRole({ [WARRIOR] = 1 }, WARRIOR, HEALER, "Horde")
		eq(result, "blocked")
		deepEq(want, { [WARRIOR] = 1 })
		_, result = M().ToggleRole({}, HUNTER, TANK, "Horde")
		eq(result, "blocked")
		_, result = M().ToggleRole({}, MAGE, MELEE, "Alliance")
		eq(result, "blocked")
	end)

	it("a class the faction does not play, an unknown class and a bad role are refused", function()
		local _, result = M().ToggleRole({}, PALADIN, TANK, "Horde")
		eq(result, "class")
		_, result = M().ToggleRole({}, SHAMAN, HEALER, "Alliance")
		eq(result, "class")
		_, result = M().ToggleRole({}, 6, TANK, "Horde")
		eq(result, "class", "Death Knight is not a class of this game")
		_, result = M().ToggleRole({}, WARRIOR, 3, "Horde")
		eq(result, "invalid")
		_, result = M().ToggleRole({}, "x", TANK, "Horde")
		eq(result, "invalid")
		local want = M().ToggleRole({}, PALADIN, HEALER, "Alliance")
		deepEq(want, { [PALADIN] = 2 })
	end)

	it("Any class is the class 0 of the map, with every role possible", function()
		local want, result = M().ToggleRole({}, 0, RANGED, "Horde")
		eq(result, "added")
		deepEq(want, { [0] = 8 })
		want = M().ToggleRole(want, 0, TANK, "Horde")
		deepEq(want, { [0] = 9 })
		want = M().ToggleRole(want, 0, RANGED, "Horde")
		deepEq(want, { [0] = 1 })
		want = M().ToggleRole(want, 0, TANK, "Horde")
		deepEq(want, {})
	end)

	it("a click on the class name ticks every role it can play, and a second click clears them", function()
		local want, result = M().ToggleClass({}, WARRIOR, "Horde")
		eq(result, "added")
		deepEq(want, { [WARRIOR] = TANK + MELEE })
		want = M().ToggleClass(want, DRUID, "Horde")
		deepEq(want, { [WARRIOR] = 5, [DRUID] = 15 })
		want, result = M().ToggleClass(want, WARRIOR, "Horde")
		eq(result, "removed")
		deepEq(want, { [DRUID] = 15 })
		want = M().ToggleClass({ [MAGE] = RANGED }, MAGE, "Horde")
		deepEq(want, {}, "a Mage with its only role on: the click clears it")
		want = M().ToggleClass({ [PRIEST] = HEALER }, PRIEST, "Horde")
		deepEq(want, { [PRIEST] = HEALER + RANGED }, "something is missing: the click ticks all")
		deepEq(M().ToggleClass({}, 0, "Horde"), { [0] = 15 })
		local _, bad = M().ToggleClass({}, PALADIN, "Horde")
		eq(bad, "class")
	end)

	it("the faction filter drops the other faction's classes and the roles a class cannot play", function()
		local want = { [PALADIN] = 7, [SHAMAN] = 14, [WARRIOR] = 15, [0] = 15, [6] = 1, [HUNTER] = TANK }
		deepEq(M().WantFor(want, "Horde"), { [SHAMAN] = 14, [WARRIOR] = 5, [0] = 15 })
		deepEq(M().WantFor(want, "Alliance"), { [PALADIN] = 7, [WARRIOR] = 5, [0] = 15 })
		deepEq(M().WantFor(nil, "Horde"), {})
		deepEq(M().WantFor("x", "Horde"), {})
	end)

	it("what the grid makes is what a published record keeps (Listing.SanitizeFull)", function()
		local want = {}
		for _, pair in ipairs({ { WARRIOR, TANK }, { WARRIOR, MELEE }, { PRIEST, HEALER }, { DRUID, RANGED }, { 0, TANK } }) do
			want = M().ToggleRole(want, pair[1], pair[2], "Horde")
		end
		deepEq(M().Want({ want = want }, "Horde"), want)
		deepEq(M().Clean({ want = want }, KEY).want, want)
		eq(M().WantCount(want), 4)
	end)

	it("a stored map is read back for the faction of the guild", function()
		deepEq(M().Want({ want = { [PALADIN] = 1, [WARRIOR] = 1 } }, "Horde"), { [WARRIOR] = 1 })
		deepEq(M().Want({}, "Horde"), {})
	end)
end)

describe("recruitment status", function()
	it("reads the status from the fields", function()
		isNil(M().Status({}))
		eq(M().Status({ rec = 0 }), 0)
		eq(M().Status({ rec = 1 }), 1)
		eq(M().Status({ rec = 2 }), 2)
		isNil(M().Status({ rec = 7 }))
	end)

	it("Closed clears the grid: a closed guild looks for nobody", function()
		local p = M().StatusPatch({ want = { [WARRIOR] = 1 } }, 0, "Horde")
		eq(p.rec, 0)
		eq(p.want, false)
	end)

	it("Open to all asks for any class and any role when the grid is empty, and keeps a grid that is there", function()
		local p = M().StatusPatch({}, 1, "Horde")
		eq(p.rec, 1)
		deepEq(p.want, { [0] = 15 })
		p = M().StatusPatch({ want = { [PRIEST] = 2 } }, 1, "Horde")
		isNil(p.want)
		p = M().StatusPatch({ want = { [PALADIN] = 1 } }, 1, "Horde")
		deepEq(p.want, { [0] = 15 }, "only a class this faction cannot play: nothing usable is there")
	end)

	it("Selected classes only changes the status", function()
		local p = M().StatusPatch({ want = { [PRIEST] = 2 } }, 2, "Horde")
		eq(p.rec, 2)
		isNil(p.want)
	end)

	it("any other value is refused", function()
		isNil(M().StatusPatch({}, 3, "Horde"))
		isNil(M().StatusPatch({}, nil, "Horde"))
		isNil(M().StatusPatch({}, "1", "Horde"))
	end)

	it("a change of the grid picks Selected classes when no status was chosen, and an empty grid is cleared", function()
		local p = M().WantPatch({}, { [PRIEST] = 2 })
		deepEq(p.want, { [PRIEST] = 2 })
		eq(p.rec, 2)
		p = M().WantPatch({ rec = 1 }, { [PRIEST] = 2 })
		isNil(p.rec, "a status that was chosen stays")
		p = M().WantPatch({ rec = 2 }, {})
		eq(p.want, false)
		isNil(p.rec)
	end)
end)

describe("the checklist and the Recruitment step", function()
	local function full(extra)
		local t = { sub = "Friendly raiders", desc = "We raid on weekends and we like to chat in voice.", lang1 = 1, lang = 1, tags = { 1, 2 },
			pace = 2, emb = { t = 2, e = 0 }, rec = 2, want = { [PRIEST] = HEALER } }
		for k, v in pairs(extra or {}) do t[k] = v end
		return t
	end
	local function without(field) return full({ [field] = "nil" }) end
	local function strip(t) for k, v in pairs(t) do if v == "nil" then t[k] = nil end end return t end

	it("looking for needs a class and a role, or Closed", function()
		eq(states(M().View(strip(without("want")), ctx())).looking, "todo")
		eq(states(M().View(full(), ctx())).looking, "ok")
		eq(states(M().View(strip(full({ want = "nil", rec = 0 })), ctx())).looking, "ok")
	end)

	it("a class the guild's faction cannot play does not count (a Paladin in a Horde guild)", function()
		eq(states(M().View(full({ want = { [PALADIN] = TANK } }), ctx())).looking, "todo")
		eq(states(M().View(full({ want = { [PALADIN] = TANK } }), ctx({ key = "TestRealm|Alliance|" .. GUILD }))).looking, "ok")
		eq(states(M().View(full({ want = { [PALADIN] = TANK, [WARRIOR] = TANK } }), ctx())).looking, "ok")
	end)

	it("the step turns green with the grid, and the Requirements step has nothing to check", function()
		local v = M().View(strip(without("want")), ctx())
		eq(v.steps[4].status, "todo")
		eq(v.first.id, "looking")
		eq(v.first.step, 4)
		eq(M().View(full(), ctx()).steps[4].status, "ok")
		eq(M().View(full(), ctx()).steps[5].status, "ok")
		eq(M().View(full({ minL = 30, minI = 100, note = "Voice required" }), ctx()).steps[5].status, "ok")
	end)
end)

describe("requirements: limits", function()
	it("the highest level comes from the client, 60 when it says nothing", function()
		eq(M().MaxLevel(), 60)
		Mock.player.maxLevel = 70
		eq(M().MaxLevel(), 70)
	end)

	it("a level is taken to a whole number from 1 to the highest level", function()
		eq(M().ClampLevel(30), 30)
		eq(M().ClampLevel("45"), 45)
		eq(M().ClampLevel(0), 1)
		eq(M().ClampLevel(-5), 1)
		eq(M().ClampLevel(75), 60)
		eq(M().ClampLevel(59.6), 60)
		isNil(M().ClampLevel(nil))
		isNil(M().ClampLevel("x"))
		isNil(M().ClampLevel(0 / 0))
	end)

	it("level 1 means no minimum and clears the field; the others are saved", function()
		eq(M().LevelPatch(1).minL, false)
		eq(M().LevelPatch(0).minL, false)
		eq(M().LevelPatch(30).minL, 30)
		eq(M().LevelPatch(500).minL, 60)
		isNil(M().LevelPatch("x"))
	end)

	it("the item level typed: digits only, 1 to 999, empty clears it", function()
		local n, how = M().ParseItemLevel("250")
		eq(n, 250) eq(how, "ok")
		n, how = M().ParseItemLevel(" 40 ")
		eq(n, 40) eq(how, "ok")
		n, how = M().ParseItemLevel("0")
		eq(n, 0) eq(how, "ok")
		n, how = M().ParseItemLevel("")
		isNil(n) eq(how, "empty")
		n, how = M().ParseItemLevel("   ")
		isNil(n) eq(how, "empty")
		n, how = M().ParseItemLevel("12a")
		isNil(n) eq(how, "invalid")
		n, how = M().ParseItemLevel("-5")
		isNil(n) eq(how, "invalid")
		n, how = M().ParseItemLevel("1500")
		eq(n, 999) eq(how, "cut")
		n, how = M().ParseItemLevel(250)
		isNil(n) eq(how, "invalid")
	end)

	it("the item level patch: 0, nothing or a negative number clear it, 999 is the highest", function()
		eq(M().ItemLevelPatch(250).minI, 250)
		eq(M().ItemLevelPatch(0).minI, false)
		eq(M().ItemLevelPatch(nil).minI, false)
		eq(M().ItemLevelPatch(-3).minI, false)
		eq(M().ItemLevelPatch(1200).minI, 999)
		eq(M().ItemLevelPatch(12.7).minI, 12)
	end)

	it("the requirements of the fields as they will be published", function()
		local r = M().Requirements({})
		eq(r.level, 1) falsy(r.hasLevel) eq(r.itemLevel, 0) falsy(r.hasItemLevel) eq(r.note, "")
		r = M().Requirements({ minL = 30, minI = 120, note = "Voice required" })
		eq(r.level, 30) truthy(r.hasLevel) eq(r.itemLevel, 120) truthy(r.hasItemLevel) eq(r.note, "Voice required")
		r = M().Requirements({ minL = 1 })
		falsy(r.hasLevel, "level 1 is no requirement")
		r = M().Requirements({ minL = 5000, minI = 5000 })
		falsy(r.hasItemLevel, "an item level above 999 is not published")
	end)

	it("the note is cut at 120 characters like the published one", function()
		eq(M().NoteMax(), 120)
		local text, changed = M().Clamp(string.rep("a", 130), M().NoteMax())
		eq(A().Normalize.Utf8Len(text), 120)
		truthy(changed)
		eq(M().Clamp("Voice required", 120), "Voice required")
		eq(M().Clamp("two\nlines", 120), "twolines")
		eq(A().Normalize.Utf8Len(M().Requirements({ note = string.rep("b", 200) }).note), 120)
	end)
end)

describe("the Discord box", function()
	local function ok(text, code, replace)
		local c = M().DiscordCheck(text)
		eq(c.state, "ok", text)
		eq(c.code, code)
		eq(c.replace, replace)
	end
	local function bad(text, reason)
		local c = M().DiscordCheck(text)
		eq(c.state, "bad", tostring(text))
		eq(c.reason, reason, tostring(text))
		isNil(c.code)
	end

	it("a code is kept as it is", function()
		ok("aurora-it", "aurora-it", nil)
		ok("ab", "ab", nil)
		ok("A1-b2", "A1-b2", nil)
		ok(string.rep("x", 32), string.rep("x", 32), nil)
	end)

	it("a whole link becomes its code", function()
		ok("https://discord.gg/aurora-it", "aurora-it", "aurora-it")
		ok("http://discord.gg/abc", "abc", "abc")
		ok("discord.gg/abc", "abc", "abc")
		ok("https://www.discord.gg/Abc", "Abc", "Abc")
		ok("HTTPS://DISCORD.GG/Abc/", "Abc", "Abc")
		ok("https://discord.com/invite/abc?event=1", "abc", "abc")
		ok("discord.com/invite/abc#top", "abc", "abc")
		ok("https://discordapp.com/invite/abc", "abc", "abc")
	end)

	it("spaces around it are dropped", function()
		ok("  abc  ", "abc", "abc")
		ok("\tdiscord.gg/abc\n", "abc", "abc")
	end)

	it("nothing typed is fine: the code is optional", function()
		eq(M().DiscordCheck("").state, "empty")
		eq(M().DiscordCheck("   ").state, "empty")
		eq(M().DiscordCheck("\t\n").state, "empty")
	end)

	it("junk is refused and the reason is said", function()
		bad("a", "short")
		bad("https://discord.gg/", "short")
		bad("https://discord.gg/a", "short")
		bad(string.rep("x", 33), "long")
		bad("https://discord.gg/" .. string.rep("x", 40), "long")
		bad("bad_code!", "chars")
		bad("ab cd", "chars")
		bad("aurora.it", "link")
		bad("https://example.com/abc", "link")
		bad("https://discord.gg/a!b", "chars")
		bad("javascript:alert(1)", "link")
		bad("ünï", "chars")
		bad(nil, "chars")
		bad(12345, "chars")
		bad({}, "chars")
	end)

	it("the link a code stands for has the fixed prefix", function()
		eq(M().DISCORD_PREFIX, "https://discord.gg/")
		eq(M().DiscordLink("aurora-it"), "https://discord.gg/aurora-it")
	end)

	it("a typed link counts as its code when saving, and junk makes the checklist red", function()
		local f = { sub = "x", desc = "d", disc = "https://discord.gg/wolves1" }
		eq(states(M().View(f, ctx())).discord, "ok")
		eq(M().Clean(f, KEY).disc, "wolves1")
		eq(states(M().View({ disc = "nope nope" }, ctx())).discord, "bad")
		eq(states(M().View({ disc = "" }, ctx())).discord, "optional")
		eq(states(M().View({}, ctx())).discord, "optional")
		eq(M().View({ disc = "a" }, ctx()).steps[6].status, "bad")
		truthy(M().Same({ disc = "https://discord.gg/wolves1" }, { disc = "wolves1" }))
	end)
end)

local function roster(members)
	Mock.guild.Set{ name = GUILD, myRank = 0, members = members or {
		{ name = "Jaina", class = "MAGE", level = 60, rank = 1 },
		{ name = "Garrosh", class = "WARRIOR", level = 58, rank = 3, online = false },
		{ name = "Thrall", class = "SHAMAN", level = 60, rank = 2 },
		{ name = "Élan", class = "ROGUE", level = 41, rank = 4 },
		{ name = "Sylvanas-Test Realm", class = "HUNTER", level = 60, rank = 2, online = false },
	} }
	return M().Roster()
end
local function names(list)
	local out = {}
	for i, m in ipairs(list) do out[i] = m.name end
	return out
end

describe("the contacts: picked from the guild roster", function()
	it("reads the roster with the class, the level and who is online", function()
		local r = roster()
		eq(#r, 6, "the character itself and five members")
		eq(r[1].name, "Testchar")
		eq(r[1].file, "WARRIOR")
		local jaina = M().FindMember(r, "Jaina")
		eq(jaina.file, "MAGE") eq(jaina.level, 60) truthy(jaina.online)
		falsy(M().FindMember(r, "Garrosh").online)
	end)

	it("has nothing without a guild or before the roster is there", function()
		Mock.guild.Leave()
		deepEq(M().Roster(), {})
	end)

	it("finds a member by the full name, the name alone or a different case", function()
		local r = roster()
		eq(M().FindMember(r, "jaina").name, "Jaina")
		eq(M().FindMember(r, "JAINA").name, "Jaina")
		eq(M().FindMember(r, "Sylvanas").name, "Sylvanas-Test Realm")
		eq(M().FindMember(r, "sylvanas-test realm").name, "Sylvanas-Test Realm")
		isNil(M().FindMember(r, "Arthas"))
		isNil(M().FindMember(r, ""))
		isNil(M().FindMember(r, nil))
		eq(M().BaseName("Sylvanas-Test Realm"), "Sylvanas")
		eq(M().BaseName("Jaina"), "Jaina")
	end)

	it("adds a member, with the name as the roster has it, in the order picked", function()
		local r = roster()
		local list, result = M().AddContact({}, "jaina", r)
		eq(result, "added")
		deepEq(list, { "Jaina" })
		list, result = M().AddContact(list, "Thrall", r)
		eq(result, "added")
		deepEq(list, { "Jaina", "Thrall" })
		list = M().AddContact(list, "Sylvanas", r)
		deepEq(list, { "Jaina", "Thrall", "Sylvanas-Test Realm" })
	end)

	it("at most 3: a fourth is refused and the list stays", function()
		local r = roster()
		local list = { "Jaina", "Thrall", "Garrosh" }
		local out, result = M().AddContact(list, "Élan", r)
		eq(result, "full")
		deepEq(out, { "Jaina", "Thrall", "Garrosh" })
		eq(M().CONTACTS_MAX, 3)
		deepEq(M().Contacts({ cont = { "A", "B", "C", "D", "E" } }), { "A", "B", "C" })
	end)

	it("the same member twice, a stranger and an empty name are refused", function()
		local r = roster()
		local _, result = M().AddContact({ "Jaina" }, "JAINA", r)
		eq(result, "repeat")
		_, result = M().AddContact({ "Sylvanas-Test Realm" }, "Sylvanas", r)
		eq(result, "repeat", "the name with and without the realm is the same member")
		_, result = M().AddContact({}, "Arthas", r)
		eq(result, "unknown")
		_, result = M().AddContact({}, "   ", r)
